  for insert to authenticated with check (
    bucket_id = 'pet-photos' and (storage.foldername(name))[1] = (select auth.uid())::text
  );
create policy "public reads pet photos" on storage.objects
  for select to anon, authenticated using (bucket_id = 'pet-photos');
create policy "owner removes pet photo" on storage.objects
  for delete to authenticated using (
    bucket_id = 'pet-photos' and (storage.foldername(name))[1] = (select auth.uid())::text
  );

