-- EncontraPet Municipal: dados fictícios e acesso por identidade verificada.
-- Execute em um projeto Supabase vazio. Nunca execute o antigo database/schema.sql
-- nesse projeto: ele é um modelo acadêmico sem as políticas de acesso abaixo.

create table public.app_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create table public.occurrences (
  id bigint generated by default as identity primary key,
  owner_id uuid references auth.users(id) on delete set null,
  type text not null check (type in ('perdido', 'encontrado')),
  species text not null check (species in ('cão', 'gato')),
  name text not null check (char_length(name) between 1 and 60),
  color text not null check (char_length(color) between 1 and 60),
  neighborhood text not null check (char_length(neighborhood) between 1 and 100),
  occurred_on date not null check (occurred_on <= current_date),
  status text not null check (status in ('em_busca_do_tutor', 'aguardando_identificacao', 'pet_reencontrado')),
  review_status text not null default 'pendente' check (review_status in ('pendente', 'aprovada', 'ocultada')),
  description text not null default '' check (char_length(description) <= 500),
  image_url text,
  image_path text,
  reported_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.contact_messages (
  id bigint generated always as identity primary key,
  occurrence_id bigint not null references public.occurrences(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  message text not null check (char_length(trim(message)) between 1 and 1000),
  created_at timestamptz not null default now()
);

create index occurrences_public_idx on public.occurrences (review_status, reported_at desc);
create index occurrences_owner_idx on public.occurrences (owner_id, reported_at desc);
create index contact_messages_occurrence_idx on public.contact_messages (occurrence_id, created_at desc);

create or replace function public.touch_occurrence()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
create trigger occurrences_touch before update on public.occurrences
  for each row execute function public.touch_occurrence();

alter table public.app_admins enable row level security;
alter table public.occurrences enable row level security;
alter table public.contact_messages enable row level security;

revoke all on public.app_admins, public.occurrences, public.contact_messages from anon, authenticated;
grant select on public.app_admins to authenticated;
grant select on public.occurrences to anon, authenticated;
grant insert on public.occurrences to authenticated;
grant update (status) on public.occurrences to authenticated;
grant select, insert on public.contact_messages to authenticated;

create policy "admin reads own membership" on public.app_admins
  for select to authenticated using (user_id = (select auth.uid()));

create policy "anyone reads approved occurrences" on public.occurrences
  for select to anon, authenticated using (review_status = 'aprovada');
create policy "tutor reads own occurrences" on public.occurrences
  for select to authenticated using (owner_id = (select auth.uid()));
create policy "admin reads all occurrences" on public.occurrences
  for select to authenticated using (
    exists (select 1 from public.app_admins where user_id = (select auth.uid()))
  );
create policy "tutor inserts pending occurrence" on public.occurrences
  for insert to authenticated with check (
    owner_id = (select auth.uid()) and review_status = 'pendente'
  );
create policy "tutor updates own occurrence" on public.occurrences
  for update to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

create policy "sender reads own messages" on public.contact_messages
  for select to authenticated using (sender_id = (select auth.uid()));
create policy "owner reads messages" on public.contact_messages
  for select to authenticated using (
    exists (select 1 from public.occurrences o
            where o.id = occurrence_id and o.owner_id = (select auth.uid()))
  );
create policy "admin reads messages" on public.contact_messages
  for select to authenticated using (
    exists (select 1 from public.app_admins where user_id = (select auth.uid()))
  );
create policy "signed-in visitor sends message to approved occurrence" on public.contact_messages
  for insert to authenticated with check (
    sender_id = (select auth.uid()) and
    exists (select 1 from public.occurrences o
            where o.id = occurrence_id and o.review_status = 'aprovada')
  );

-- A conta administradora não recebe permissão direta para alterar review_status.
-- Esta função verifica a associação e altera somente a coluna de moderação.
create or replace function public.moderate_occurrence(p_id bigint, p_review_status text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if (select auth.uid()) is null or not exists (
    select 1 from public.app_admins where user_id = (select auth.uid())
  ) then
    raise exception 'Acesso não autorizado';
  end if;
  if p_review_status not in ('aprovada', 'ocultada') then
    raise exception 'Situação de revisão inválida';
  end if;
  update public.occurrences set review_status = p_review_status where id = p_id;
  if not found then raise exception 'Ocorrência não encontrada'; end if;
end;
$$;
revoke all on function public.moderate_occurrence(bigint, text) from public, anon;
grant execute on function public.moderate_occurrence(bigint, text) to authenticated;

